"""
ledgerhound.findings.models
========================

Dataclasses for structured findings.

Sample-frame design
-------------------
Every finding declares the *sample frame* under which its claim holds.
This is what stops the agent from silently mixing population and
sample-level statistics. Three modes:

* ``WITHIN_STRATUM``      -- claim holds within one stratum of the sample.
                            No re-weighting needed.
* ``CROSS_STRATUM``        -- claim mixes strata; re-weighting was applied
                            (sampling weights honored).
* ``POPULATION_ESTIMATE`` -- claim is an extrapolation to population.
                            Requires explicit weights or rollup source.

Phase-2 hook: ``DERIVED_SAMPLE`` -- a frame whose sampling spec was itself
generated from earlier findings (importance sampling). Tracking it
distinctly is what prevents bias amplification when findings feed back.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional


# -- Enums --------------------------------------------------


class SampleFrame(str, Enum):
    """Which interpretive frame the finding's numbers live in."""

    WITHIN_STRATUM       = "within_stratum"
    CROSS_STRATUM        = "cross_stratum"
    POPULATION_ESTIMATE  = "population_estimate"
    DERIVED_SAMPLE       = "derived_sample"   # Phase 2 hook
    UNSPECIFIED          = "unspecified"


class PriorResult(str, Enum):
    """Outcome of testing a prior with this finding."""

    SURVIVES   = "survives"
    COLLAPSES  = "collapses"
    SHIFTS     = "shifts"        # holds but in modified form
    UNTESTED   = "untested"


# -- Dataclasses --------------------------------------------


@dataclass
class Evidence:
    """The reproducible trail behind a finding.

    At least one of (query, code, chart_path) should be non-empty;
    otherwise the finding is hearsay, not analysis.
    """

    summary: str = ""                       # one-line 'what was computed'
    query: Optional[str] = None             # SQL run (DuckDB / Trino)
    code: Optional[str] = None              # Python snippet (pandas/cuDF)
    result: Optional[Any] = None            # serialisable result
    chart_path: Optional[str] = None        # filesystem path to PNG/SVG
    n_rows_examined: Optional[int] = None   # how much data fed the result

    def is_empty(self) -> bool:
        """True if this finding is unsupported by anything reproducible."""
        return not (self.query or self.code or self.chart_path)


def _make_finding_id() -> str:
    """ID format: f_YYYYMMDD_<short-uuid>. Sortable + readable."""
    today = datetime.now(timezone.utc).strftime("%Y%m%d")
    return f"f_{today}_{uuid.uuid4().hex[:8]}"


@dataclass
class Finding:
    """A single, structured analytical finding.

    Parameters
    ----------
    id              : Stable identifier (auto-generated by default).
    claim           : One-sentence statement of what was found.
    evidence        : Reproducible trail (Evidence object).
    sample_frame    : Which interpretation regime applies to this claim.
    sample_frame_note: Free-text qualifier on the frame
                      (e.g. "weighted by inclusion probability").
    confidence      : 0.0-1.0; subjective but documented.
    dataset         : Which dataset this was derived from.
    priors_tested   : List of L3 prior names this finding tested.
    priors_result   : Outcome (survives / collapses / shifts / untested).
    derived_from    : IDs of findings this builds on.
    enables_sampling_for : Phase-2 hook -- datasets whose sampling spec
                           could be derived from this finding.
    tags            : Free-form tags.
    timestamp       : ISO-8601 UTC.
    """

    claim: str
    evidence: Evidence = field(default_factory=Evidence)
    sample_frame: SampleFrame = SampleFrame.UNSPECIFIED
    sample_frame_note: str = ""
    confidence: float = 0.5
    dataset: Optional[str] = None
    priors_tested: list[str] = field(default_factory=list)
    priors_result: PriorResult = PriorResult.UNTESTED
    derived_from: list[str] = field(default_factory=list)
    enables_sampling_for: list[str] = field(default_factory=list)
    tags: list[str] = field(default_factory=list)
    # V3-026: populated by FindingsLog.consolidate() when 2+ near-duplicate
    # findings merge into one -- [{finding_id, query, code, chart_path,
    # summary}, ...], one entry per source finding that carried real
    # evidence. Empty for an ordinary (unmerged) finding. See has_evidence().
    evidence_links: list[dict] = field(default_factory=list)
    id: str = field(default_factory=_make_finding_id)
    timestamp: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    # Phase-2 hook: structured sample-frame validation result, populated
    # automatically by FindingsLog if a SampleFrameValidator is wired in.
    # Keys: is_valid (bool), warnings (list[str]), errors (list[str]),
    # required_promotion (str | None), suggested_fix (str).
    validation: Optional[dict] = None

    # Phase-2 hook: stratum the finding is bound to (for WITHIN_STRATUM).
    stratum: Optional[str] = None
    # Parent sample reference (for DERIVED_SAMPLE).
    parent_sample: Optional[str] = None
    # Whether the analyst documented the weights used (for CROSS_STRATUM).
    weights_documented: bool = False

    # -- invariants / validation -----------------------------

    def __post_init__(self) -> None:
        if not (0.0 <= self.confidence <= 1.0):
            raise ValueError(f"confidence must be in [0,1]; got {self.confidence}")
        if not self.claim.strip():
            raise ValueError("claim must be non-empty")

    def has_evidence(self) -> bool:
        """True if this finding is backed by something reproducible --
        either its own evidence (query/code/chart_path, same trio
        Evidence.is_empty() checks) or, for a merged finding, at least one
        evidence_links entry inherited from a source finding."""
        return bool(self.evidence_links) or not self.evidence.is_empty()

    # -- serialisation --------------------------------------

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "timestamp": self.timestamp,
            "dataset": self.dataset,
            "claim": self.claim,
            "evidence": {
                "summary": self.evidence.summary,
                "query": self.evidence.query,
                "code": self.evidence.code,
                "result": self.evidence.result,
                "chart_path": self.evidence.chart_path,
                "n_rows_examined": self.evidence.n_rows_examined,
            },
            "sample_frame": self.sample_frame.value,
            "sample_frame_note": self.sample_frame_note,
            "stratum": self.stratum,
            "parent_sample": self.parent_sample,
            "weights_documented": self.weights_documented,
            "confidence": self.confidence,
            "priors_tested": list(self.priors_tested),
            "priors_result": self.priors_result.value,
            "derived_from": list(self.derived_from),
            "enables_sampling_for": list(self.enables_sampling_for),
            "tags": list(self.tags),
            "evidence_links": list(self.evidence_links),
            "validation": self.validation,
        }

    @classmethod
    def from_dict(cls, d: dict) -> Finding:
        ev = d.get("evidence") or {}
        return cls(
            id=d.get("id") or _make_finding_id(),
            timestamp=d.get("timestamp") or datetime.now(timezone.utc).isoformat(),
            dataset=d.get("dataset"),
            claim=d["claim"],
            evidence=Evidence(
                summary=ev.get("summary", ""),
                query=ev.get("query"),
                code=ev.get("code"),
                result=ev.get("result"),
                chart_path=ev.get("chart_path"),
                n_rows_examined=ev.get("n_rows_examined"),
            ),
            sample_frame=SampleFrame(d.get("sample_frame", "unspecified")),
            sample_frame_note=d.get("sample_frame_note", ""),
            stratum=d.get("stratum"),
            parent_sample=d.get("parent_sample"),
            weights_documented=bool(d.get("weights_documented", False)),
            confidence=float(d.get("confidence", 0.5)),
            priors_tested=list(d.get("priors_tested") or []),
            priors_result=PriorResult(d.get("priors_result", "untested")),
            derived_from=list(d.get("derived_from") or []),
            enables_sampling_for=list(d.get("enables_sampling_for") or []),
            tags=list(d.get("tags") or []),
            evidence_links=list(d.get("evidence_links") or []),
            validation=d.get("validation"),
        )
