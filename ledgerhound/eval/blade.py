"""
ledgerhound.eval.blade
===================

V5-007. Score Ledgerhound against BLADE -- an external benchmark, graded by
someone else, on the thing we actually claim.

Every number in `ledgerhound/eval/` so far is scored against our own goldens. That
is useful for regression and worth nothing to a sceptical reviewer, who has no
reason to believe our answer key. BLADE (arXiv 2408.09667, Gu et al.) grades
*the decisions inside an open-ended analysis* -- which control variables a
real analyst chose, which transformations they actually applied -- rather than
a final answer. That is the closest external proxy for our product claim that
exists.

The task
--------
BLADE's MCQ split poses `select_neg`: several analysis decisions are shown for
one research question, all but one taken from real analysts who worked that
dataset; the remaining one was generated by a language model. The model must
identify the fake.

It is a good test precisely because it is hard to fake. Producing a
plausible-sounding control variable is easy -- that is what the distractor is.
Telling a plausible one from a *real* one requires knowing how analysis
decisions are actually made, which is the judgement Ledgerhound claims to
enforce.

Two arms
--------
`bare` runs the question with a neutral instruction. `ledgerhound` prepends the
discipline this project enforces -- grain, sample frame, not-reported labels,
leakage-from-downstream-artifacts, effect size versus significance. Running
both against the same model on the same items isolates the only variable worth
measuring: **does our discipline make analysis judgement better, or do we just
believe it does?**

An honest result includes the case where it does not.
"""

from __future__ import annotations

import json
import random
import re
from dataclasses import asdict, dataclass, field
from pathlib import Path

# The rules Ledgerhound enforces, stated as analysis guidance rather than as tool
# refusals. Lifted from the same source as the shell's discipline prompts so
# the arm tests OUR method, not a prompt written to win a benchmark.
LEDGERHOUND_DISCIPLINE = """\
You are an experienced fraud/observational-data analyst. Judge these options \
the way a working analyst would, holding to the following:

- A real analyst's decision is usually SPECIFIC and slightly awkward: it names \
  a concrete column, handles a known quirk in this dataset, or drops a \
  particular bad row. A generated one tends to be tidy, general, and \
  reasonable-sounding without being anchored to anything in the data.
- Controls exist to block a specific confound the analyst had in mind. A \
  control proposed because it is "good practice", with no mechanism stated, \
  is a tell.
- Real analysts worry about GRAIN (per-unit vs per-observation), about \
  SAMPLE FRAME (is this a within-group result being read as a population \
  one), and about LEAKAGE (is this variable downstream of the outcome).
- Real analysts distinguish an effect that is statistically detectable from \
  one large enough to matter.
- Rationales written by real analysts are often terse, informal, or partly \
  missing. Polished, complete, evenly-structured prose is a tell.
"""

BARE_INSTRUCTION = (
    "You are a data analyst evaluating choices made during a data analysis."
)

_ANSWER = re.compile(r"\b([1-9][0-9]?)\b")


@dataclass
class MCQItem:
    dataset: str
    kind: str                 # "cvar" | "transform"
    question: str             # the research question / conceptual variable
    options: list[str] = field(default_factory=list)
    rationales: list[str] = field(default_factory=list)
    correct_index: int = -1

    def prompt_body(self) -> str:
        lines = [f"Dataset: {self.dataset}", f"Context: {self.question}", ""]
        lines.append("Options:")
        for i, (opt, rat) in enumerate(zip(self.options, self.rationales), 1):
            lines.append(f"{i}. {opt}")
            if rat and rat.strip():
                lines.append(f"   Analyst's stated reason: {rat.strip()}")
        return "\n".join(lines)


@dataclass
class ArmResult:
    arm: str
    n: int = 0
    correct: int = 0
    unparsed: int = 0
    errors: int = 0
    truncated: int = 0        # ran out of tokens mid-reasoning: harness fault
    by_kind: dict = field(default_factory=dict)
    per_item: list = field(default_factory=list)

    @property
    def accuracy(self) -> float:
        return self.correct / self.n if self.n else 0.0

    def to_dict(self) -> dict:
        return asdict(self)


def _opt_text(o: dict) -> str:
    """A cvar option carries `cvar_str`; a transform option carries `code`."""
    return str(o.get("cvar_str") or o.get("code") or "").strip()


def load_items(datasets_dir: str | Path, *, limit: int | None = None,
               seed: int = 0) -> list[MCQItem]:
    """Read BLADE's `mcq_dataset.json` files into a flat list.

    Option order is shuffled per item with a fixed seed: BLADE stores the
    generated option in a consistent position often enough that an unshuffled
    run would measure position bias rather than judgement.
    """
    root = Path(datasets_dir)
    rng = random.Random(seed)
    items: list[MCQItem] = []

    for path in sorted(root.glob("*/mcq_dataset.json")):
        name = path.parent.name
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            continue

        groups: list[tuple[str, list]] = []
        cvar = data.get("mcqs_cvar") or []
        if isinstance(cvar, list):
            groups.append(("cvar", cvar))
        tf = data.get("mcqs_transform") or {}
        if isinstance(tf, dict):
            for _var, qs in tf.items():
                if isinstance(qs, list):
                    groups.append(("transform", qs))
        elif isinstance(tf, list):
            groups.append(("transform", tf))

        for kind, questions in groups:
            for q in questions:
                if not isinstance(q, dict) or q.get("mc_type") != "select_neg":
                    continue
                opts = [o for o in (q.get("options") or []) if isinstance(o, dict)]
                correct = q.get("correct_answer") or {}
                if len(opts) < 2 or not isinstance(correct, dict):
                    continue
                target = _opt_text(correct)
                if not target:
                    continue

                order = list(range(len(opts)))
                rng.shuffle(order)
                shuffled = [opts[i] for i in order]
                texts = [_opt_text(o) for o in shuffled]
                try:
                    idx = texts.index(target)
                except ValueError:
                    continue     # answer key not among the options -- skip

                items.append(MCQItem(
                    dataset=name, kind=kind,
                    question=str(q.get("coneptual_var_str")
                                 or q.get("conceptual_var_str")
                                 or "which choice was not made by a real analyst"),
                    options=texts,
                    rationales=[str(o.get("rationale") or "") for o in shuffled],
                    correct_index=idx))

    if limit is not None:
        items = items[:limit]
    return items


def build_prompt(item: MCQItem, arm: str) -> str:
    header = LEDGERHOUND_DISCIPLINE if arm == "ledgerhound" else BARE_INSTRUCTION
    return (
        f"{header}\n\n"
        f"{item.prompt_body()}\n\n"
        f"Exactly one of these {len(item.options)} options was NOT written by "
        f"a real analyst working this dataset -- it was generated by a "
        f"language model. Identify it.\n\n"
        f"Answer with the option NUMBER only, nothing else."
    )


def _parse(reply: str, n_options: int) -> int:
    """Return a 0-based index, or -1 if the reply cannot be read."""
    for m in _ANSWER.finditer(reply or ""):
        v = int(m.group(1))
        if 1 <= v <= n_options:
            return v - 1
    return -1


# Reasoning models spend their budget thinking before they answer, and a
# budget too small yields an EMPTY reply with finish_reason="length" -- which
# scores as unparsed, i.e. as a benchmark result rather than a harness fault.
# Measured on deepseek-flash: empty at 3000, answers at 8000. Anything below
# this silently reports 0% for a model that is working fine.
DEFAULT_MAX_TOKENS = 8000


def _score_one(llm, item: MCQItem, arm: str, max_tokens: int) -> dict:
    """One question. Returns a record; never raises."""
    try:
        resp = llm.generate(
            [{"role": "user", "content": build_prompt(item, arm)}],
            max_tokens=max_tokens)
    except Exception as e:  # noqa: BLE001
        return {"dataset": item.dataset, "kind": item.kind,
                "error": f"{type(e).__name__}: {e}"}

    reply = resp.content or ""
    rec = {"dataset": item.dataset, "kind": item.kind,
           "correct": item.correct_index,
           "finish": getattr(resp, "finish_reason", ""),
           "reply": reply.strip()[:40]}
    if not reply.strip() and rec["finish"] == "length":
        # Distinguish "the model was cut off mid-thought" from "the model
        # answered something we could not read". Only the second is a real
        # unparsed; the first means max_tokens is too low, and calling it a
        # wrong answer would report a harness fault as a benchmark score.
        rec["truncated"] = True
    rec["picked"] = _parse(reply, len(item.options))
    return rec


def run_arm(llm, items: list[MCQItem], arm: str, *,
            max_tokens: int = DEFAULT_MAX_TOKENS, progress=None,
            workers: int = 8) -> ArmResult:
    """Score one arm. Parallel by default: reasoning models take tens of
    seconds per item, and 145 items serially is over an hour of wall clock
    for a benchmark that is entirely I/O-bound."""
    from concurrent.futures import ThreadPoolExecutor

    res = ArmResult(arm=arm)
    records: list[dict | None] = [None] * len(items)

    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {pool.submit(_score_one, llm, item, arm, max_tokens): i
                   for i, item in enumerate(items)}
        done = 0
        from concurrent.futures import as_completed
        for fut in as_completed(futures):
            records[futures[fut]] = fut.result()
            done += 1
            if progress:
                progress(done, len(items), res)

    # Tally in item order so `per_item` is reproducible regardless of the
    # order the threads happened to finish in.
    for item, rec in zip(items, records):
        rec = rec or {"dataset": item.dataset, "kind": item.kind,
                      "error": "no result"}
        res.n += 1
        kind = res.by_kind.setdefault(item.kind, {"n": 0, "correct": 0})
        kind["n"] += 1
        if "error" in rec:
            res.errors += 1
        elif rec.get("truncated"):
            res.truncated += 1
        elif rec.get("picked", -1) < 0:
            res.unparsed += 1
        elif rec["picked"] == item.correct_index:
            res.correct += 1
            kind["correct"] += 1
        res.per_item.append(rec)
    return res


def chance_rate(items: list[MCQItem]) -> float:
    """Accuracy a coin-flipping model would reach -- the only number that
    makes an accuracy figure interpretable."""
    if not items:
        return 0.0
    return sum(1.0 / len(i.options) for i in items) / len(items)


def render(results: list[ArmResult], items: list[MCQItem]) -> str:
    lines = ["BLADE select_neg -- spot the decision a model wrote", ""]
    lines.append(f"Items: {len(items)}  |  chance: {chance_rate(items):.1%}")
    lines.append("")
    lines.append(f"{'arm':<12}{'accuracy':<12}{'correct':<12}"
                 f"{'unparsed':<11}{'truncated':<12}{'errors'}")
    for r in results:
        lines.append(f"{r.arm:<12}{r.accuracy:>7.1%}     "
                     f"{r.correct:>3}/{r.n:<8}{r.unparsed:<11}"
                     f"{r.truncated:<12}{r.errors}")
    if any(r.truncated for r in results):
        lines.append("")
        lines.append("WARNING: truncated replies present -- the model ran out "
                     "of tokens before answering. Raise max_tokens; these are "
                     "NOT wrong answers and this accuracy is not a result.")
    if len(results) == 2:
        delta = results[1].accuracy - results[0].accuracy
        lines.append("")
        lines.append(f"delta ({results[1].arm} - {results[0].arm}): "
                     f"{delta:+.1%}")
    lines.append("")
    for r in results:
        parts = [f"{k}: {v['correct']}/{v['n']}" for k, v in sorted(r.by_kind.items())]
        lines.append(f"  {r.arm:<12} " + "  ".join(parts))
    return "\n".join(lines)
