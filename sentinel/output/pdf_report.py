"""
sentinel.output.pdf_report
============================

Generates a polished PDF report with embedded charts, stats tables,
and executive summary.  Uses fpdf2 (pure Python, no LaTeX or
system deps -- works on Kubeflow/Linux out of the box).

Usage::

    from sentinel.output.pdf_report import save_pdf_report
    save_pdf_report("report.pdf", findings=..., summary=..., digest=...)
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any

from fpdf import FPDF


class SentinelPDF(FPDF):
    """Custom PDF with Sentinel branding."""

    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.set_auto_page_break(auto=True, margin=20)

    @staticmethod
    def _safe(text: str) -> str:
        """Replace unicode chars that Latin-1 can't encode."""
        return (text
                .replace("\u2014", "-")   # em dash
                .replace("\u2013", "-")   # en dash
                .replace("\u2018", "'")   # left quote
                .replace("\u2019", "'")   # right quote
                .replace("\u201c", '"')   # left double quote
                .replace("\u201d", '"')   # right double quote
                .replace("\u2022", "*")   # bullet
                .replace("\u2026", "...") # ellipsis
                .replace("\u2713", "[OK]") # checkmark
                .replace("\u2717", "[X]")  # cross
                .replace("\u00d7", "x")   # multiplication sign
                )

    def _cell(self, w, h, txt, **kw):
        """Wrapper that sanitizes text."""
        super().cell(w, h, self._safe(str(txt)), **kw)

    def _mcell(self, w, h, txt, **kw):
        """Wrapper that sanitizes text."""
        super().multi_cell(w, h, self._safe(str(txt)), **kw)

    def header(self):
        if self.page_no() == 1:
            return  # title page has custom header
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 8, "Sentinel - Agentic EDA Report", align="L")
        self.cell(0, 8, f"Page {self.page_no()}", align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(200, 200, 200)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Generated by Sentinel v0.1 - {datetime.now().strftime('%Y-%m-%d %H:%M')}",
                  align="C")

    def title_page(self, title: str, subtitle: str = "",
                   stats: dict | None = None):
        """Create a branded title page."""
        self.add_page()
        self.ln(50)

        # Title
        self.set_font("Helvetica", "B", 28)
        self.set_text_color(30, 64, 175)  # blue
        self.cell(0, 15, self._safe(title), align="C", new_x="LMARGIN", new_y="NEXT")

        # Subtitle
        self.set_font("Helvetica", "", 14)
        self.set_text_color(100, 100, 100)
        self.cell(0, 10, subtitle or "Automated Fraud Analytics Report",
                  align="C", new_x="LMARGIN", new_y="NEXT")

        # Date
        self.ln(5)
        self.set_font("Helvetica", "", 11)
        self.cell(0, 8, datetime.now().strftime("%B %d, %Y"),
                  align="C", new_x="LMARGIN", new_y="NEXT")

        # Stats cards
        if stats:
            self.ln(20)
            self._stats_row(stats)

        # Divider
        self.ln(15)
        self.set_draw_color(30, 64, 175)
        self.set_line_width(0.8)
        self.line(60, self.get_y(), 150, self.get_y())

    def _stats_row(self, stats: dict):
        """Render a row of stats like a dashboard."""
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(80, 80, 80)

        items = list(stats.items())[:6]  # max 6 stats
        col_w = 190 / len(items)

        # Values
        self.set_font("Helvetica", "B", 18)
        self.set_text_color(30, 64, 175)
        for _, val in items:
            self.cell(col_w, 12, str(val), align="C")
        self.ln()

        # Labels
        self.set_font("Helvetica", "", 8)
        self.set_text_color(120, 120, 120)
        for label, _ in items:
            self.cell(col_w, 6, label, align="C")
        self.ln()

    def section_header(self, text: str):
        """Phase/section header with colored bar."""
        self.ln(6)
        self.set_fill_color(30, 64, 175)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 12)
        self.cell(0, 9, f"  {text}", fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(3)
        self.set_text_color(0, 0, 0)

    def finding_block(self, question: str, finding: str, status: str = "success",
                      charts: list[str] | None = None):
        """Render a single finding with question, answer, and charts."""
        # Check if we need a new page (leave room for content)
        if self.get_y() > 240:
            self.add_page()

        # Status icon
        icon = "[OK]" if status == "success" else "[FAIL]"
        icon_color = (34, 197, 94) if status == "success" else (239, 68, 68)

        # Question
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*icon_color)
        self.cell(12, 7, icon)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 7, self._safe(question), new_x="LMARGIN", new_y="NEXT")

        # Finding text
        self.set_font("Helvetica", "", 9)
        self.set_text_color(60, 60, 60)
        # Truncate very long findings
        if len(finding) > 1500:
            finding = finding[:1500] + "..."
        # Clean up markdown artifacts
        finding = finding.replace("**", "").replace("##", "").replace("###", "")
        self.multi_cell(0, 5, self._safe(finding), new_x="LMARGIN", new_y="NEXT")

        # Embed charts
        for chart_path in (charts or []):
            p = Path(chart_path)
            if p.exists() and p.suffix.lower() in (".png", ".jpg", ".jpeg"):
                if self.get_y() > 180:
                    self.add_page()
                try:
                    self.ln(3)
                    # Fit chart to page width with margin
                    self.image(str(p), x=15, w=180)
                    self.ln(3)
                except Exception:
                    self.set_font("Helvetica", "I", 8)
                    self.cell(0, 5, f"[Chart: {p.name}]",
                              new_x="LMARGIN", new_y="NEXT")

        # Separator
        self.ln(2)
        self.set_draw_color(220, 220, 220)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(3)

    def summary_section(self, summary: str):
        """Executive summary with highlight box."""
        if self.get_y() > 200:
            self.add_page()

        self.section_header("Executive Summary")

        self.set_fill_color(240, 245, 255)
        self.set_draw_color(30, 64, 175)

        self.set_font("Helvetica", "", 10)
        self.set_text_color(30, 30, 30)

        # Clean markdown
        summary = summary.replace("**", "").replace("##", "").replace("###", "")
        if len(summary) > 3000:
            summary = summary[:3000] + "..."

        self.multi_cell(0, 6, self._safe(summary), new_x="LMARGIN", new_y="NEXT")

    def quality_table(self, digest: dict):
        """Render data quality overview table."""
        dq = digest.get("data_quality", {})
        cp = digest.get("column_priority", {})

        self.section_header("Data Quality Overview")

        self.set_font("Helvetica", "", 9)
        self.set_text_color(40, 40, 40)

        # Quality score
        score = dq.get("score", "?")
        self.set_font("Helvetica", "B", 11)
        color = (34, 197, 94) if score >= 80 else (245, 158, 11) if score >= 50 else (239, 68, 68)
        self.set_text_color(*color)
        self.cell(0, 8, f"Quality Score: {score}/100", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(40, 40, 40)

        # Issues table
        self.set_font("Helvetica", "B", 9)
        self.set_fill_color(240, 240, 240)
        self.cell(40, 7, "Column", border=1, fill=True)
        self.cell(80, 7, "Issue", border=1, fill=True)
        self.cell(70, 7, "Action", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

        self.set_font("Helvetica", "", 8)
        for issue in dq.get("critical", [])[:8]:
            self.cell(40, 6, str(issue.get("column", ""))[:20], border=1)
            self.cell(80, 6, str(issue.get("issue", ""))[:45], border=1)
            self.cell(70, 6, str(issue.get("action", ""))[:35], border=1,
                      new_x="LMARGIN", new_y="NEXT")
        for issue in dq.get("warnings", [])[:5]:
            self.cell(40, 6, str(issue.get("column", ""))[:20], border=1)
            self.cell(80, 6, str(issue.get("issue", ""))[:45], border=1)
            self.cell(70, 6, str(issue.get("action", ""))[:35], border=1,
                      new_x="LMARGIN", new_y="NEXT")

        # High-signal columns
        high = cp.get("high", [])
        if high:
            self.ln(5)
            self.set_font("Helvetica", "B", 9)
            self.cell(0, 7, f"High-Signal Columns ({len(high)}):",
                      new_x="LMARGIN", new_y="NEXT")
            self.set_font("Helvetica", "", 8)
            self.multi_cell(0, 5, ", ".join(high[:20]),
                            new_x="LMARGIN", new_y="NEXT")

        # Drop candidates
        drop = cp.get("drop_candidates", [])
        if drop:
            self.ln(3)
            self.set_font("Helvetica", "B", 9)
            self.set_text_color(239, 68, 68)
            self.cell(0, 7, f"Drop Candidates ({len(drop)}):",
                      new_x="LMARGIN", new_y="NEXT")
            self.set_font("Helvetica", "", 8)
            self.set_text_color(40, 40, 40)
            self.multi_cell(0, 5, ", ".join(drop),
                            new_x="LMARGIN", new_y="NEXT")


def save_pdf_report(
    path: str,
    findings: list[dict],
    summary: str = "",
    digest: dict | None = None,
    charts: list[str] | None = None,
    title: str = "Sentinel EDA Report",
    elapsed_ms: float = 0.0,
    analyses_run: int = 0,
    analyses_succeeded: int = 0,
) -> str:
    """Generate and save a PDF report with embedded charts."""
    pdf = SentinelPDF()

    # Build stats for title page
    ov = (digest or {}).get("overview", {})
    dq = (digest or {}).get("data_quality", {})
    stats = {}
    if ov.get("rows"):
        stats["Rows"] = f"{ov['rows']:,}"
    if ov.get("columns"):
        stats["Columns"] = str(ov["columns"])
    stats["Quality"] = f"{dq.get('score', '?')}/100"
    stats["Analyses"] = f"{analyses_succeeded}/{analyses_run}"
    stats["Runtime"] = f"{elapsed_ms/1000:.0f}s"
    stats["Charts"] = str(len(charts or []))

    # Title page
    pdf.title_page(title, stats=stats)

    # Data quality page
    if digest:
        pdf.add_page()
        pdf.quality_table(digest)

    # Findings by phase
    cur_phase = ""
    for f in findings:
        if f.get("phase", "") != cur_phase:
            cur_phase = f["phase"]
            if pdf.get_y() > 220:
                pdf.add_page()
            pdf.section_header(cur_phase)

        pdf.finding_block(
            question=f.get("question", ""),
            finding=f.get("finding", f.get("error", "Failed")),
            status=f.get("status", "failed"),
            charts=f.get("charts", []),
        )

    # Executive summary
    if summary:
        pdf.add_page()
        pdf.summary_section(summary)

    # Save
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    pdf.output(str(p))
    return str(p)
